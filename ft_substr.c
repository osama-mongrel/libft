#include "libft.h"

char	*ft_substr(char const *s, unsigned int start, size_t len)
{
	char	*sptr;
	size_t	size;

	if (!s)
		return (NULL);
	if (start >= ft_strlen(s))
		return (ft_strdup(""));
	size = ft_strlen(s + start);
	if (size > len)
		size = len;
	sptr = malloc(sizeof(char) * (size + 1));
	if (!sptr)
		return (NULL);
	ft_strlcpy(sptr, s + start, size + 1);
	return (sptr);
}
